// Build the local calculation engine from the user's GradKUya checkout.
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const source = resolve(process.argv[2] ?? '');
if (!process.argv[2]) throw new Error('Usage: node packaging/build_gradkuya.mjs <GradKUya checkout>');
const require = createRequire(join(source, 'package.json'));
const ts = require('typescript');
const destination = resolve(dirname(fileURLToPath(import.meta.url)), '../skills/university-agent/integrations/gradkuya/engine');
const files = ['lib/transcript.ts', 'lib/graduation.ts', 'lib/handbooks.ts', 'lib/schedule.ts', 'lib/kupis.ts', 'data/requirements.ts'];
const omitted = new Set(['ensureHandbook', 'fetchHandbook', 'pending', 'boardUrl', 'headers',
  'getAllCourses', 'getVacancies', 'getRows', 'parseCatalog', 'getText', 'inBatches',
  'ORIGIN', 'BASE', 'CACHE_SECONDS', 'courses']);
const manifest = { repository: 'https://github.com/K-Lunatic/GradKUya', files: {},
  adaptations: ['Offline calculations only', 'Failed courses do not satisfy required courses', 'Exact admission-year handbook required', 'Sample timetable removed'] };

for (const file of files) {
  let text = await readFile(join(source, 'src', file), 'utf8');
  manifest.files[file] = createHash('sha256').update(text).digest('hex');
  if (file === 'lib/graduation.ts') {
    const before = 'const completed = new Set(transcript.courses.map((course) => course.code));';
    if (!text.includes(before)) throw new Error('Graduation source changed. Review the failed-course adaptation.');
    text = text.replace(before, 'const completed = new Set(transcript.courses.filter((course) => !["F", "NP"].includes(course.grade)).map((course) => course.code));');
  }
  if (file === 'lib/handbooks.ts') {
    const before = '.filter((handbook) => handbook.year <= admissionYear)';
    if (!text.includes(before)) throw new Error('Handbook source changed. Review the admission-year adaptation.');
    text = text.replace(before, '.filter((handbook) => handbook.year === admissionYear)');
  }
  const parsed = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true);
  const keep = parsed.statements.filter((statement) => {
    if (ts.isImportDeclaration(statement) && statement.moduleSpecifier.text.includes('pdf-server')) return false;
    if (ts.isFunctionDeclaration(statement)) return !omitted.has(statement.name?.text);
    if (ts.isVariableStatement(statement)) return !statement.declarationList.declarations.some((declaration) => omitted.has(declaration.name.getText(parsed)));
    return true;
  });
  const selected = ts.createPrinter().printFile(ts.factory.updateSourceFile(parsed, keep));
  let output = ts.transpileModule(selected, { compilerOptions: { target: ts.ScriptTarget.ES2023, module: ts.ModuleKind.ESNext } }).outputText;
  output = output.replace(/from\s+(["'])(\.\.?\/[^"']+)\1/g, (_match, quote, path) =>
    `from ${quote}${path.endsWith('.json') ? path : path.replace(/\.ts$/, '') + '.mjs'}${quote}`);
  if (file === 'lib/kupis.ts') output += '\nexport { toCourse };\n';
  const target = join(destination, file.replace(/\.ts$/, '.mjs'));
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, '// Generated by packaging/build_gradkuya.mjs. See ../manifest.json.\n' + output);
}
const data = await readFile(join(source, 'src/data/handbooks/index.json'));
manifest.files['data/handbooks/index.json'] = createHash('sha256').update(data).digest('hex');
await mkdir(join(destination, 'data/handbooks'), { recursive: true });
await writeFile(join(destination, 'data/handbooks/index.json'), data);
await writeFile(join(destination, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log('GradKUya local engine built.');
